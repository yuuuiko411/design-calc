import { beforeEach, describe, expect, it, vi } from 'vitest'
import { render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import App from './App'

beforeEach(() => { window.history.replaceState(null, '', '/'); })
const region = (name: string) => within(screen.getByRole('region', { name: new RegExp(`^${name}`) }))

describe('calculator workflows', () => {
  it('updates conversion live and prevents invalid copies', async () => {
    const user = userEvent.setup()
    render(<App />)
    const tool = region('Unit Converter')
    expect(tool.getByLabelText('変換結果')).toHaveTextContent('1.5rem')
    await user.clear(tool.getByLabelText('ルート文字サイズ'))
    await user.type(tool.getByLabelText('ルート文字サイズ'), '20')
    expect(tool.getByLabelText('変換結果')).toHaveTextContent('1.2rem')
    await user.clear(tool.getByLabelText('変換する値'))
    expect(tool.getByRole('button', { name: '結果をコピー' })).toBeDisabled()
    expect(tool.getByLabelText('変換する値')).toHaveAttribute('aria-invalid', 'true')
    expect(tool.getAllByText('変換する値を入力してください。').length).toBeGreaterThan(0)
    expect(tool.queryByText(/NaN|Infinity/)).not.toBeInTheDocument()
  })
  it('switches unit direction', async () => {
    const user = userEvent.setup()
    render(<App />)
    const tool = region('Unit Converter')
    await user.click(tool.getByRole('button', { name: 'rem → px' }))
    await user.clear(tool.getByLabelText('変換する値'))
    await user.type(tool.getByLabelText('変換する値'), '1.25')
    expect(tool.getByLabelText('変換結果')).toHaveTextContent('20px')
  })
  it('copies values and announces success', async () => {
    const user = userEvent.setup()
    const write = vi.spyOn(navigator.clipboard, 'writeText').mockResolvedValue()
    render(<App />)
    await user.click(region('Unit Converter').getByRole('button', { name: '結果をコピー' }))
    expect(write).toHaveBeenCalledWith('1.5rem')
    expect(await screen.findByText('コピーしました。クリップボードから貼り付けできます。')).toBeInTheDocument()
  })
  it('announces clipboard failure', async () => {
    const user = userEvent.setup()
    vi.spyOn(navigator.clipboard, 'writeText').mockRejectedValue(new Error('Permission denied'))
    render(<App />)
    await user.click(region('Unit Converter').getByRole('button', { name: '結果をコピー' }))
    expect(await screen.findByText('コピーできませんでした。結果のテキストを選択してコピーしてください。')).toBeInTheDocument()
  })
  it('keeps values across navigation and responds to browser history', async () => {
    const user = userEvent.setup()
    render(<App />)
    await user.clear(region('Unit Converter').getByLabelText('変換する値'))
    await user.type(region('Unit Converter').getByLabelText('変換する値'), '32')
    await user.click(screen.getByRole('link', { name: /Spacing Scale/ }))
    await waitFor(() => expect(screen.getByRole('heading', { name: /^Spacing Scale/ })).toBeVisible())
    window.history.back()
    await waitFor(() => expect(screen.getByRole('heading', { name: /^Unit Converter/ })).toBeVisible())
    expect(region('Unit Converter').getByLabelText('変換する値')).toHaveValue('32')
  })
  it('renders direct hash links', () => {
    window.history.replaceState(null, '', '/#type')
    render(<App />)
    expect(screen.getByRole('heading', { name: /^Type Scale/ })).toBeVisible()
  })
  it('skip link focuses main content and preserves the selected tool', async () => {
    const user = userEvent.setup()
    window.history.replaceState(null, '', '/#type')
    render(<App />)
    await user.click(screen.getByRole('link', { name: 'メインコンテンツへ移動' }))
    expect(screen.getByRole('main')).toHaveFocus()
    expect(window.location.hash).toBe('#type')
    expect(screen.getByRole('heading', { name: /^Type Scale/ })).toBeVisible()
  })
  it('generates spacing CSS and snaps ties upward', async () => {
    const user = userEvent.setup()
    const write = vi.spyOn(navigator.clipboard, 'writeText').mockResolvedValue()
    window.history.replaceState(null, '', '/#spacing')
    render(<App />)
    const tool = region('Spacing Scale')
    await user.clear(tool.getByLabelText('近似する余白'))
    await user.type(tool.getByLabelText('近似する余白'), '20')
    expect(tool.getByText('基準 × 3')).toBeInTheDocument()
    await user.click(tool.getByRole('button', { name: 'スケールを一括コピー' }))
    expect(write).toHaveBeenCalledWith(expect.stringContaining('--space-3: 24px;'))
  })
  it('shows actual type sizes, individual CSS, and readability warnings', async () => {
    const user = userEvent.setup()
    const write = vi.spyOn(navigator.clipboard, 'writeText').mockResolvedValue()
    window.history.replaceState(null, '', '/#type')
    render(<App />)
    const tool = region('Type Scale')
    const sample = tool.getByRole('region', { name: 'H2の文字見本、25px' })
    expect(sample.firstChild).toHaveStyle({ fontSize: '25px' })
    await user.click(tool.getByRole('button', { name: 'SmallのCSS値をコピー' }))
    expect(write).toHaveBeenCalledWith('font-size: 12.8px;')
    await user.clear(tool.getByLabelText('基準文字サイズ'))
    await user.type(tool.getByLabelText('基準文字サイズ'), '8')
    expect(tool.getByText(/12px未満の文字があります/)).toBeInTheDocument()
  })
  it('keeps the fixed edge when changing ratios and switches reference side', async () => {
    const user = userEvent.setup()
    window.history.replaceState(null, '', '/#aspect')
    render(<App />)
    const tool = region('Aspect Ratio')
    expect(tool.getByLabelText('幅')).toHaveValue('1200')
    await user.click(tool.getByRole('button', { name: '4:3' }))
    expect(tool.getByLabelText('幅')).toHaveValue('1200')
    expect(tool.getByText('900')).toBeInTheDocument()
    await user.click(tool.getByRole('button', { name: '高さを基準にする' }))
    expect(tool.getByLabelText('高さ')).toHaveValue('900')
    await user.clear(tool.getByLabelText('高さ'))
    await user.type(tool.getByLabelText('高さ'), '600')
    expect(tool.getByText('800')).toBeInTheDocument()
  })
  it('blocks aspect result overflow', async () => {
    const user = userEvent.setup()
    window.history.replaceState(null, '', '/#aspect')
    render(<App />)
    const tool = region('Aspect Ratio')
    await user.click(tool.getByRole('button', { name: '9:16' }))
    await user.clear(tool.getByLabelText('幅'))
    await user.type(tool.getByLabelText('幅'), '100000')
    expect(tool.getByText(/計算後の幅・高さが/)).toBeInTheDocument()
    expect(tool.getByRole('button', { name: 'サイズをコピー' })).toBeDisabled()
  })
})
